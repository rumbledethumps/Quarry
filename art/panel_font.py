SHADOW = (24, 32, 42)
CREAM = [(246, 242, 232), (246, 242, 232), (236, 231, 219), (224, 218, 205),
         (212, 205, 191), (200, 193, 178), (188, 180, 165)]
SHORT = [(242, 150, 120), (242, 150, 120), (230, 132, 104), (216, 116, 90),
         (202, 102, 78), (188, 90, 68), (174, 80, 60)]


def glyph(shape, colors):
    """An 8x8 cell: the glyph at 0, 0, its shadow a pixel down and right."""
    cell = [[PLATE] * 8 for _ in range(8)]
    on = {(x, y) for y, line in enumerate(shape) for x, c in enumerate(line) if c == '#'}
    for x, y in on:
        if (x + 1, y + 1) not in on:
            cell[y + 1][x + 1] = SHADOW
    for x, y in on:
        cell[y][x] = colors[y]
    return cell


def pip(filled):
    """A pip: a gold block lit from the upper left, or an empty socket."""
    cell = [[PLATE] * 8 for _ in range(8)]
    for y in range(2, 6):
        for x in range(1, 6):
            if filled:
                cell[y][x] = [(255, 222, 140), (240, 186, 80), (214, 150, 56), (170, 108, 36)][y - 2]
            else:
                cell[y][x] = (34, 44, 58)
        cell[y][6] = SHADOW if filled else (78, 94, 112)
    for x in range(1, 7):
        cell[6][x] = SHADOW if filled else (78, 94, 112)
    return cell


def main():
    cells = [glyph(GLYPHS[c], CREAM) if c != ' ' else [[PLATE] * 8 for _ in range(8)] for c in FONT]
    cells += [glyph(GLYPHS[c], SHORT) for c in '0123456789']
    cells += [pip(True), pip(False)]
    rows = [[v for cell in cells for c in cell[y] for v in c + (255,)] for y in range(8)]
    write_png(os.path.join(HERE, 'panel-font.png'), 8 * len(cells), 8, 6, rows)


if __name__ == '__main__':
    main()
